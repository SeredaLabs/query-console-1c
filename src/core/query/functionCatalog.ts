export interface FunctionLeaf {
  label: string;
  /** Текст, що вставляється; `<Имя>` — місце для заповнення (редактор виразів
   * перетворює їх на поля сніпета). */
  template: string;
  /** Короткий приклад використання для довідки редактора виразів (необов'язковий). */
  example?: string;
}

export interface FunctionGroup {
  label: string;
  children: (FunctionGroup | FunctionLeaf)[];
}

const fn = (label: string, template: string, example?: string): FunctionLeaf =>
  example ? { label, template, example } : { label, template };
const op = (symbol: string): FunctionLeaf => ({ label: symbol, template: symbol });

