import { describe, it, expect } from 'vitest';
import { tokenize } from '../../src/core/query/sdblLexer';

describe('sdblLexer — незакрытые строковые/дата литералы', () => {
  it('валидная строка с экранированной кавычкой "" по-прежнему токенизируется как одна строка', () => {
    const tokens = tokenize('ВЫБРАТЬ "a""b" КАК В');
    const str = tokens.find((t) => t.type === 'string');
    expect(str?.value).toBe('"a""b"');
  });

  it('незакрытая строка (нет закрывающей кавычки до конца текста) — лексическая ошибка', () => {
    expect(() => tokenize('ВЫБРАТЬ "оops')).toThrow(/незакрытый строковый литерал/);
  });

  it('строка, обрывающаяся сразу после экранированной пары кавычек — тоже незакрытая', () => {
    // "abc"" — экранированная пара "" поглощается, дальше конец текста без реального закрытия.
    expect(() => tokenize('ВЫБРАТЬ "abc""')).toThrow(/незакрытый строковый литерал/);
  });

  it('строка с тремя кавычками подряд перед концом текста — валидна (экранированная пара + настоящее закрытие)', () => {
    const tokens = tokenize('ВЫБРАТЬ "abc"""');
    const str = tokens.find((t) => t.type === 'string');
    expect(str?.value).toBe('"abc"""');
  });

  it('незакрытый литерал даты — лексическая ошибка', () => {
    expect(() => tokenize("ВЫБРАТЬ '2024-01-01")).toThrow(/незакрытый литерал даты/);
  });

  it('валидный литерал даты по-прежнему токенизируется без ошибок', () => {
    const tokens = tokenize("ВЫБРАТЬ '20240101'");
    const date = tokens.find((t) => t.type === 'date');
    expect(date?.value).toBe("'20240101'");
  });
});
